let currentLanguage: Language = "ar"

export function setLanguage(lang: Language) {
  currentLanguage = lang
  if (typeof window !== "undefined") {
    localStorage.setItem("oec_language", lang)
    // تحديث اتجاه الصفحة حسب اللغة
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr"
    document.documentElement.lang = lang
  }
}

export function getLanguage(): Language {
  if (typeof window !== "undefined") {
    const saved = localStorage.getItem("oec_language")
    if (saved === "ar" || saved === "en") {
      currentLanguage = saved
    }
  }
  return currentLanguage
}

export function t(key: string, lang?: Language): string {
  const language = lang || currentLanguage
  return translations[language]?.[key] ?? translations.ar[key] ?? key
}

// دالة مساعدة: ترجمة مع استبدال متغيرات
export function tf(key: string, vars: Record<string, string | number>, lang?: Language): string {
  let text = t(key, lang)
  for (const [k, v] of Object.entries(vars)) {
    text = text.replace(new RegExp(`\\{${k}\\}`, "g"), String(v))
  }
  return text
}
